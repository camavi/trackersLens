const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { ChatProjectWorkspace } = require('../core/desktop/chat-project-workspace.cjs');
const { createTlCore } = require('../core/desktop/tl-core.cjs');

test('project folder grant is chat-scoped and cannot follow paths outside it', async (context) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tl-project-reader-'));
  const outside = fs.mkdtempSync(path.join(os.tmpdir(), 'tl-project-outside-'));
  context.after(() => { fs.rmSync(root, { recursive: true, force: true }); fs.rmSync(outside, { recursive: true, force: true }); });
  fs.writeFileSync(path.join(root, 'main.js'), 'const answer = 42;\n');
  fs.writeFileSync(path.join(root, 'binary.bin'), Buffer.from([0, 1, 2]));
  fs.writeFileSync(path.join(outside, 'private.txt'), 'private');
  fs.symlinkSync(path.join(outside, 'private.txt'), path.join(root, 'outside-link'));
  const reader = new ChatProjectWorkspace({ selectDirectory: async () => root });
  const core = createTlCore({ adapters: { chatProject: reader } });
  const selected = await core.request('desktop.chatProject.chooseFolder', { chatId: 'chat-one' });
  assert.equal(selected.selected, true);
  assert.equal(JSON.stringify(selected).includes(root), false);
  const listed = await core.request('desktop.chatProject.listDirectory', { chatId: 'chat-one', folderId: selected.folderId });
  assert.equal(listed.entries.find(entry => entry.name === 'main.js').type, 'file');
  assert.equal(listed.entries.find(entry => entry.name === 'outside-link').type, 'symlink');
  const read = await core.request('desktop.chatProject.readTextFile', { chatId: 'chat-one', folderId: selected.folderId, relativePath: 'main.js' });
  assert.equal(read.text, 'const answer = 42;\n');
  const search = await core.request('desktop.chatProject.searchText', { chatId: 'chat-one', folderId: selected.folderId, query: 'answer' });
  assert.deepEqual(search.matches.map(match => [match.relativePath, match.lineNumber, match.line]), [['main.js', 1, 'const answer = 42;']]);
  assert.ok(search.skipped.some(item => item.relativePath === 'outside-link' && item.reason === 'symlink'));
  assert.ok(search.skipped.some(item => item.relativePath === 'binary.bin' && item.reason === 'binary'));
  const editArgs = { chatId: 'chat-one', folderId: selected.folderId, relativePath: 'main.js', expectedSha256: read.sha256, content: 'const answer = 43;\n' };
  await assert.rejects(core.request('desktop.chatProject.applyTextEdit', { ...editArgs, confirmed: true }), /reviewed preview/);
  const preview = await core.request('desktop.chatProject.previewTextEdit', editArgs);
  assert.equal(preview.before, read.text);
  assert.equal(preview.after, editArgs.content);
  await assert.rejects(core.request('desktop.chatProject.applyTextEdit', { ...editArgs, previewToken: preview.previewToken }), /confirmation/);
  const applied = await core.request('desktop.chatProject.applyTextEdit', { ...editArgs, previewToken: preview.previewToken, confirmed: true });
  assert.equal(applied.applied, true);
  assert.equal(fs.readFileSync(path.join(root, 'main.js'), 'utf8'), editArgs.content);
  await assert.rejects(core.request('desktop.chatProject.applyTextEdit', { ...editArgs, previewToken: preview.previewToken, confirmed: true }), /reviewed preview/);
  const stale = await core.request('desktop.chatProject.previewTextEdit', { ...editArgs, expectedSha256: applied.sha256, content: 'next' });
  fs.writeFileSync(path.join(root, 'main.js'), 'external change');
  await assert.rejects(core.request('desktop.chatProject.applyTextEdit', { ...editArgs, expectedSha256: applied.sha256, content: 'next', previewToken: stale.previewToken, confirmed: true }), /changed since review/);
  await assert.rejects(core.request('desktop.chatProject.readTextFile', { chatId: 'chat-two', folderId: selected.folderId, relativePath: 'main.js' }), /grant/);
  await assert.rejects(core.request('desktop.chatProject.readTextFile', { chatId: 'chat-one', folderId: selected.folderId, relativePath: '../private.txt' }), /outside/);
  await assert.rejects(core.request('desktop.chatProject.readTextFile', { chatId: 'chat-one', folderId: selected.folderId, relativePath: 'outside-link' }), /outside/);
  await assert.rejects(core.request('desktop.chatProject.readTextFile', { chatId: 'chat-one', folderId: selected.folderId, relativePath: 'binary.bin' }), /Binary/);
});

test('new project files require review and never overwrite concurrent creations', async context => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tl-project-create-'));
  context.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.mkdirSync(path.join(root, 'test'));
  const workspace = new ChatProjectWorkspace({ selectDirectory: async () => root });
  const selected = await workspace.chooseFolder({ chatId: 'create' });
  const args = { chatId: 'create', folderId: selected.folderId, relativePath: 'test/new.js', expectedSha256: 'absent', content: '' };
  const preview = workspace.previewTextEdit(args);
  assert.equal(preview.creating, true);
  assert.equal(fs.existsSync(path.join(root, 'test/new.js')), false);
  assert.throws(() => workspace.applyTextEdit({ ...args, previewToken: preview.previewToken }), /confirmation/);
  const applied = workspace.applyTextEdit({ ...args, previewToken: preview.previewToken, confirmed: true });
  assert.equal(applied.applied, true);
  assert.equal(fs.readFileSync(path.join(root, 'test/new.js'), 'utf8'), '');
  assert.throws(() => workspace.previewTextEdit(args), /already exists/);
  const next = { ...args, relativePath: 'concurrent.js', content: 'proposed' };
  const reviewed = workspace.previewTextEdit(next);
  fs.writeFileSync(path.join(root, 'concurrent.js'), 'user change');
  assert.throws(() => workspace.applyTextEdit({ ...next, previewToken: reviewed.previewToken, confirmed: true }), /already exists/);
  assert.equal(fs.readFileSync(path.join(root, 'concurrent.js'), 'utf8'), 'user change');
  assert.throws(() => workspace.previewTextEdit({ ...args, relativePath: '../outside.js' }), /relative path/);
  assert.throws(() => workspace.previewTextEdit({ ...args, relativePath: 'missing/new.js' }), /ENOENT/);
});
